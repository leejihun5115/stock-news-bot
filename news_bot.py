def _shorten_headline(text, max_len=60):
    if len(text) <= max_len:
        return text
    for punct in ["다.", "다…", "습니다.", "다!", "?"]:
        idx = text.find(punct, 0, max_len + 20)
        if idx != -1:
            return text[: idx + len(punct)]
    return text[:max_len].rstrip() + "…"


