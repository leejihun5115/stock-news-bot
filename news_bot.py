def check_dart_disclosures(current_time_str):
    if not DART_API_KEY:
        return

    today_str = datetime.datetime.now().strftime("%Y%m%d")
    page_no = 1
    max_pages = 5
    scanned = 0
    sent = 0

    while page_no <= max_pages:
        url = (
            "https://opendart.fss.or.kr/api/list.json"
            f"?crtfc_key={DART_API_KEY}&bgn_de={today_str}"
            f"&page_no={page_no}&page_count=100"
        )
        data = None
        for attempt in range(2):
            try:
                res = requests.get(url, timeout=10)
                if res.status_code == 200:
                    data = res.json()
                    break
            except (requests.RequestException, ValueError):
                pass
            if attempt == 0:
                time.sleep(1)
        if not data or data.get("status") != "000":
            break

        for item in data.get("list", []):
            corp_name = item.get("corp_name", "")
            report_nm = item.get("report_nm", "")
            rcept_no = item.get("rcept_no", "")
            stock_code = item.get("stock_code", "")
            full_title = f"[{corp_name}] {report_nm}"

            if not full_title or is_already_sent(full_title):
                continue

            scanned += 1
            is_rumor = any(k in report_nm for k in DART_RUMOR_KEYWORDS)
            is_listed = (
                corp_name in ALL_LISTED_COMPANIES
                or any(root in corp_name for root in DART_WATCH_COMPANIES)
            )

            # 🚫 비상장사는 풍문류를 포함해서 전부 제외 (상장 여부를 최우선으로 확인)
            if not is_listed:
                mark_as_sent(full_title)
                continue

            # 풍문/조회공시는 (상장사에 한해서) 그대로 노출.
            if is_rumor:
                detail_url = f"https://dart.fss.or.kr/dsaf001/main.do?rcpNo={rcept_no}"
                mark_as_sent(full_title)  # 🚫 먼저 등록해서 중복 전송 차단
                send_telegram_message(
                    full_title, detail_url, current_time_str, 1,
                    False, False, False, False,
                    is_disclosure=False, is_rumor=True,
                    show_link_below=True,
                )
                sent += 1
                continue

            report_text = _dart_document_text(rcept_no)
            if not report_text:
                # ⚠️ 원문 텍스트를 못 가져오면 지분율/배당금/비율 요약(extra_notes)이
                # 전부 빈 채로 나갈 수밖에 없습니다. 왜 요약이 안 붙었는지 바로
                # 알 수 있도록 로그를 남깁니다 (예전엔 조용히 넘어가서 원인 파악이 안 됐음).
                print(f"[DART 원문 조회 실패] {corp_name} / {report_nm} (rcept_no={rcept_no}) - 원문을 못 가져와 요약 없이 발송됩니다.")
            should_expose, reason = dart_should_expose(report_nm, report_text, stock_code)
            if not should_expose:
                mark_as_sent(full_title)
                continue

            detail_url = f"https://dart.fss.or.kr/dsaf001/main.do?rcpNo={rcept_no}"
            mark_as_sent(full_title)  # 🚫 먼저 등록해서 중복 전송 차단

            # 🏢 회사명 (시가총액) 헤더를 제목 위에 붙임 - 시총 조회 실패하면 그냥 회사명만
            mcap = _dart_market_cap_eok(stock_code)
            # 🗓 "몇 분기 실적인지" 원문에서 찾아서 명확하게 붙임 (못 찾으면 report_nm만)
            quarter_label = _dart_extract_quarter_label(report_text, report_nm)
            # 🧹 "현금ㆍ현물배당결정(자회사의 주요경영사항)"처럼 뒤에 괄호로 붙는 부가설명은
            # 제목을 너무 길고 산만하게 만들어서 잘라냄 (핵심 공시 유형명만 남김)
            clean_report_nm = re.sub(r"\([^)]*\)\s*$", "", report_nm).strip()
            report_line = f"{quarter_label} {clean_report_nm}" if quarter_label else clean_report_nm
            if mcap:
                display_title = f"🏢 {corp_name} (시가총액 {_eok_comma_label(mcap)})\n👀 {report_line}"
            else:
                display_title = f"🏢 {corp_name}\n👀 {report_line}"

            # 💰 배당결정이면 배당금액을, 📐 주식병합/분할/감자결정이면 비율을,
            # 📐 대량보유상황보고서면 지분율을, 📐 최대주주변경이면 누구→누구인지를,
            # 📐 무상증자면 배정비율을, 📐 그 외 금액이 있는 구조적 이벤트(전환사채,
            # 유형자산양수도, 신규시설투자, 소송제기, 공개매수 등)는 관련 금액을
            # 원문에서 찾아서 본문(highlight_suffix) 영역에 추가함. 이런 "구조적
            # 이벤트" 유형은 원래 %가 없어서 본문이 비어있었는데, 이제 채워짐.
            extra_notes = [
                x for x in (
                    _dart_dividend_amount_label(report_nm, report_text),
                    _dart_merge_split_ratio_label(report_nm, report_text),
                    _dart_shareholding_label(report_nm, report_text),
                    _dart_major_shareholder_change_label(report_nm, report_text),
                    _dart_free_stock_ratio_label(report_nm, report_text),
                    _dart_generic_amount_label(report_nm, report_text),
                    _dart_schedule_label(report_text),  # 📅 유형 무관 공통 일정 정보
                ) if x
            ]
            if extra_notes:
                reason = (reason + "\n" if reason else "") + "\n".join(extra_notes)
            elif report_text and "대량보유상황보고서" in report_nm:
                # 원문은 정상적으로 받아왔는데도 지분율을 못 찾은 경우 - 이 공시가
                # 예상과 다른 문서 포맷(표 구조 등)일 수 있으므로 로그로 남겨서
                # 다음에 패턴을 더 보강할 수 있게 합니다.
                print(f"[DART 지분율 파싱 실패] {corp_name} (rcept_no={rcept_no}) - 원문은 받았지만 보유비율 패턴을 못 찾음.")

            send_telegram_message(
                display_title, detail_url, current_time_str, 1,
                False, False, False, False,
                is_disclosure=True, is_rumor=False,
                highlight_suffix=reason or "",
                show_link_below=True,
            )
            sent += 1

        total_page = int(data.get("total_page", 1) or 1)
        if page_no >= total_page:
            break
        page_no += 1

    print(f"[{current_time_str}] DART 공시: 신규 {scanned}건 확인, 강한재료 {sent}건 전송")


